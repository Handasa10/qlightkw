#!/usr/bin/env python3
"""Builds CODE.md: the complete source of the QUALITY LIGHT video engine, every file in full.
Run from the repo root:  python3 docs/video-handoff/make_code_md.py"""
import os, pathlib
K = pathlib.Path('skills/quality-light-video-generator')
OUT = pathlib.Path('docs/video-handoff/CODE.md')
LANG = {'.js': 'javascript', '.py': 'python', '.sh': 'bash', '.html': 'html', '.json': 'json', '.md': 'markdown', '.yaml': 'yaml'}
groups = [
    ('1. Reel engine (2D/motion template) — toolkit/reel/template', sorted((K / 'toolkit/reel/template').glob('*.*'))),
    ('2. Reel tools', [K / 'toolkit/reel/new.sh', K / 'toolkit/reel/thumbs.py']),
    ('3. 3D engine (three.js) — toolkit/3d', [K / 'toolkit/3d' / f for f in ('head.html', 'tail.html', 'shoot.js', 'fly.js', 'package.json')] + [K / 'toolkit/package.json']),
    ('4. 3D scene bodies (every scene) — toolkit/3d/bodies', sorted((K / 'toolkit/3d/bodies').glob('*.html'))),
    ('5. Studio / bot client — toolkit', [K / 'toolkit' / f for f in ('studio.py', 'tts.py', 'watch.py')]),
    ('6. Static post template — toolkit/post', sorted((K / 'toolkit/post').glob('*.*'))),
    ('7. Finished reel examples (part.js) — toolkit/reel/examples', sorted((K / 'toolkit/reel/examples').glob('*.*'))),
    ('8. Recent real reels (part.js + music.json) — docs/video-handoff/samples', sorted(pathlib.Path('docs/video-handoff/samples').rglob('*.*'))),
]
skip = {'.png', '.ttf', '.jpg', '.mp4', '.wav'}
n = 0
with OUT.open('w', encoding='utf-8') as o:
    o.write('# QUALITY LIGHT video engine — full source\n\nEvery file below is complete (not shortened). Generated by `make_code_md.py`.\n'
            'Binary assets (Cairo .ttf fonts, logo PNGs) are in the zip, not here.\n\n## Contents\n\n')
    for title, files in groups:
        o.write(f'- {title} ({len([f for f in files if f.suffix not in skip])} files)\n')
    for title, files in groups:
        o.write(f'\n\n# {title}\n')
        for f in files:
            if f.suffix in skip or not f.is_file(): continue
            body = f.read_text(encoding='utf-8')
            fence = '````' if '```' in body else '```'
            o.write(f'\n## `{f}`\n\n{fence}{LANG.get(f.suffix, "")}\n{body.rstrip()}\n{fence}\n'); n += 1
print(f'{OUT}: {n} files, {OUT.stat().st_size // 1024} KB')
